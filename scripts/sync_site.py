#!/usr/bin/env python3
"""Sync the website (docs/) with the report's design system.

The canonical design system lives in the package, next to the v3 report
that inlines it:

    src/ragaudit/report/templates/v3/design.css   tokens and shared components
    src/ragaudit/report/templates/v3/design.js    copy buttons, pill tabs, slides
    src/ragaudit/report/templates/v3/_slides.jinja the 6-picture widget

GitHub Pages has no build step, so the site gets plain copies:

    docs/assets/ragaudit.css, docs/assets/ragaudit.js
    the hero slides in docs/index.html, between the ragaudit:slides markers
    (rendered from the macro with the dark palette)

Run after editing any canonical file:   python scripts/sync_site.py
Check without writing (used by tests):  python scripts/sync_site.py --check
"""

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
V3 = REPO / "src" / "ragaudit" / "report" / "templates" / "v3"
DOCS = REPO / "docs"
INDEX = DOCS / "index.html"
SLIDES_START = "<!-- ragaudit:slides:start (generated by scripts/sync_site.py; do not edit) -->"
SLIDES_END = "<!-- ragaudit:slides:end -->"


def _header(source: str) -> str:
    text = (
        f"GENERATED FILE: do not edit. Source of truth: src/ragaudit/report/templates/v3/{source}\n"
        "   Regenerate with: python scripts/sync_site.py"
    )
    return f"/* {text} */\n"


def hero_slides() -> str:
    from jinja2 import Environment, FileSystemLoader

    env = Environment(loader=FileSystemLoader(str(V3.parent)), autoescape=True)
    macro = env.get_template("v3/_slides.jinja").module.slides
    return str(macro("hero", dark=True)).strip()


def expected() -> dict[Path, str]:
    files = {
        DOCS / "assets" / "ragaudit.css": _header("design.css") + (V3 / "design.css").read_text(encoding="utf-8"),
        DOCS / "assets" / "ragaudit.js": _header("design.js") + (V3 / "design.js").read_text(encoding="utf-8"),
    }
    index = INDEX.read_text(encoding="utf-8")
    if SLIDES_START not in index or SLIDES_END not in index:
        raise SystemExit(f"{INDEX} has no slides markers")
    before, rest = index.split(SLIDES_START, 1)
    _, after = rest.split(SLIDES_END, 1)
    files[INDEX] = before + SLIDES_START + "\n" + hero_slides() + "\n" + SLIDES_END + after
    return files


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, text in expected().items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        stale.append(path)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"Wrote {path.relative_to(REPO)}")
    if check and stale:
        print("Out of date (run python scripts/sync_site.py): " + ", ".join(str(p.relative_to(REPO)) for p in stale))
        return 1
    if not stale:
        print("The site is in sync with the report's design system.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
